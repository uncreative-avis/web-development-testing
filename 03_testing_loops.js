// Loops are about as you'd expect.

// formatted basically the same as C#!
for (let count = 1; count <= 10; count++) { // counts from 1-10, inclusive (<=)
    console.log(`Count: ${count}`)
}

// while loops as well; just need a let variable

let example = 0
while (example < 20) {
    example += 2
    console.log(`Loop Count: ${example}`)
}